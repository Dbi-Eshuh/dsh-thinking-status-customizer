/** Normalize DSH locale ids to the languages shipped by this plugin. */
export function resolveLocale(locale: string): LocaleId {
  return locale.toLowerCase().split('-')[0] === 'en' ? 'en' : 'zh'
}

/** Translate one key with visible placeholders for any missing parameter. */
export function translate(locale: string, key: MessageKey, params?: MessageParams): string {
  const template = (resolveLocale(locale) === 'en' ? en : zh)[key]
  if (params === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match)
}
